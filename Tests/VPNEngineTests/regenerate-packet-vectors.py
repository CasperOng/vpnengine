#!/usr/bin/env python3
"""Regenerate Tests/VPNEngineTests/PacketVectors.swift.

Builds complete IPv4 and IPv6 packets - UDP, TCP and ICMP - and computes every
checksum with an independent implementation of RFC 1071 written directly from
the RFC's pseudocode. The Swift engine must reproduce these bytes exactly when
it recomputes checksums, so the two implementations cross-check each other.

IPv4 addresses are the RFC 5737 documentation ranges; IPv6 addresses are from
RFC 3849.
"""
import struct, sys


def checksum(data: bytes) -> int:
    """RFC 1071 one's complement checksum."""
    if len(data) % 2:
        data += b"\x00"
    total = 0
    for i in range(0, len(data), 2):
        total += (data[i] << 8) | data[i + 1]
    while total >> 16:
        total = (total & 0xFFFF) + (total >> 16)
    return (~total) & 0xFFFF


def ipv4_header(src, dst, protocol, payload_len, ttl=64, ident=0x1234, flags_fragment=0x4000):
    total_len = 20 + payload_len
    header = struct.pack("!BBHHHBBH4s4s", 0x45, 0, total_len, ident, flags_fragment,
                         ttl, protocol, 0, src, dst)
    value = checksum(header)
    return header[:10] + struct.pack("!H", value) + header[12:]


def udp_segment(src, dst, sport, dport, payload, version, next_header=17):
    length = 8 + len(payload)
    if version == 4:
        pseudo = src + dst + b"\x00" + bytes([next_header]) + struct.pack("!H", length)
    else:
        pseudo = src + dst + struct.pack("!I", length) + b"\x00\x00\x00" + bytes([next_header])
    value = checksum(pseudo + struct.pack("!HHHH", sport, dport, length, 0) + payload)
    if value == 0:
        value = 0xFFFF
    return struct.pack("!HHHH", sport, dport, length, value) + payload


def tcp_segment(src, dst, sport, dport, payload, version, next_header=6, seq=0x11223344):
    offset_flags = (5 << 12) | 0x18  # data offset 5 words, PSH|ACK
    header = struct.pack("!HHIIHHHH", sport, dport, seq, 0, offset_flags, 0x2000, 0, 0)
    length = len(header) + len(payload)
    if version == 4:
        pseudo = src + dst + b"\x00" + bytes([next_header]) + struct.pack("!H", length)
    else:
        pseudo = src + dst + struct.pack("!I", length) + b"\x00\x00\x00" + bytes([next_header])
    value = checksum(pseudo + header + payload)
    header = struct.pack("!HHIIHHHH", sport, dport, seq, 0, offset_flags, 0x2000, value, 0)
    return header + payload


def ipv6_header(src, dst, next_header, payload_len, hop_limit=64):
    return struct.pack("!IHBB16s16s", 0x60000000, payload_len, next_header, hop_limit, src, dst)


def hexbytes(text):
    return bytes.fromhex(text.replace(" ", ""))


# ---------------------------------------------------------------- IPv4 / UDP
v4_source = bytes([192, 0, 2, 10])
v4_destination = bytes([198, 51, 100, 20])
udp_payload = b"wireguard engine test payload"
udp4 = udp_segment(v4_source, v4_destination, 41000, 53, udp_payload, 4)
ipv4_udp = ipv4_header(v4_source, v4_destination, 17, len(udp4)) + udp4

# ---------------------------------------------------------------- IPv4 / TCP
tcp_payload = b"GET / HTTP/1.1\r\nHost: example\r\n\r\n"
tcp4 = tcp_segment(v4_source, v4_destination, 51000, 443, tcp_payload, 4)
ipv4_tcp = ipv4_header(v4_source, v4_destination, 6, len(tcp4), ident=0x4321) + tcp4

# ---------------------------------------------------------------- IPv4 / ICMP
icmp = bytes([8, 0, 0, 0, 0x1C, 0x46, 0x00, 0x01]) + bytes(range(1, 25))
icmp_value = checksum(icmp)
icmp = icmp[:2] + struct.pack("!H", icmp_value) + icmp[4:]
ipv4_icmp = ipv4_header(v4_source, v4_destination, 1, len(icmp), ident=0x7777) + icmp

# ---------------------------------------------------------------- IPv6 / UDP
v6_source = hexbytes("20010db8 00000000 00000000 00000001")
v6_destination = hexbytes("20010db8 00000000 00000000 00000002")
udp6 = udp_segment(v6_source, v6_destination, 41000, 53, udp_payload, 6)
ipv6_udp = ipv6_header(v6_source, v6_destination, 17, len(udp6)) + udp6

# ------------------------------------------------- IPv6 / UDP behind options
# Hop-by-Hop Options header: next header 17, length 0 -> (0 + 1) * 8 = 8 bytes.
hop_by_hop = bytes([17, 0, 0x01, 0x04, 0, 0, 0, 0])
ipv6_options_udp = ipv6_header(v6_source, v6_destination, 0, len(hop_by_hop) + len(udp6)) \
    + hop_by_hop + udp6

# ---------------------------------------------------------------- IPv6 / TCP
tcp6 = tcp_segment(v6_source, v6_destination, 51000, 443, tcp_payload, 6)
ipv6_tcp = ipv6_header(v6_source, v6_destination, 6, len(tcp6)) + tcp6

out = []
w = out.append
w("//")
w("//  PacketVectors.swift")
w("//")
w("//  Complete IP packets with every checksum filled in.")
w("//")
w("//  Generated by `regenerate-packet-vectors.py`, which builds the packets and")
w("//  computes the checksums with an independent implementation of RFC 1071. The")
w("//  Swift engine must reproduce these bytes exactly when it recomputes")
w("//  checksums, so the two implementations check each other.")
w("//")
w("")
w("import Foundation")
w("")
w("/// Whole packets used by the IP packet tests.")
w("enum PacketVectors {")
w("")
w('    /// IPv4 with a UDP payload. Source 192.0.2.10, destination 198.51.100.20.')
w(f'    static let ipv4UDP = "{ipv4_udp.hex()}"')
w('')
w('    /// IPv4 with a TCP payload carrying an HTTP request line.')
w(f'    static let ipv4TCP = "{ipv4_tcp.hex()}"')
w('')
w('    /// IPv4 with an ICMP echo request. The engine does not touch ICMP')
w('    /// checksums, which this vector pins.')
w(f'    static let ipv4ICMP = "{ipv4_icmp.hex()}"')
w('')
w('    /// IPv6 with a UDP payload.')
w(f'    static let ipv6UDP = "{ipv6_udp.hex()}"')
w('')
w('    /// IPv6 with a Hop-by-Hop Options header in front of the UDP payload,')
w('    /// so the transport checksum pseudo-header must use the *last* next')
w('    /// header value (17) rather than the first (0).')
w(f'    static let ipv6OptionsUDP = "{ipv6_options_udp.hex()}"')
w('')
w('    /// IPv6 with a TCP payload.')
w(f'    static let ipv6TCP = "{ipv6_tcp.hex()}"')
w('')
w('    /// Addresses and ports used by the vectors, for building expectations.')
w(f'    static let ipv4Source = "{v4_source.hex()}"')
w(f'    static let ipv4Destination = "{v4_destination.hex()}"')
w(f'    static let ipv6Source = "{v6_source.hex()}"')
w(f'    static let ipv6Destination = "{v6_destination.hex()}"')
w(f'    static let udpPayloadLength = {len(udp_payload)}')
w(f'    static let tcpPayloadLength = {len(tcp_payload)}')
w("}")

sys.stdout.write("\n".join(out) + "\n")
